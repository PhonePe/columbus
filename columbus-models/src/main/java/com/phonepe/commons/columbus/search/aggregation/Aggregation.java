package com.phonepe.commons.columbus.search.aggregation;

import com.fasterxml.jackson.annotation.JsonClassDescription;
import com.fasterxml.jackson.annotation.JsonPropertyDescription;
import com.fasterxml.jackson.annotation.JsonSubTypes;
import com.fasterxml.jackson.annotation.JsonTypeInfo;
import com.phonepe.commons.columbus.search.aggregation.bucket.FilterAggregation;
import com.phonepe.commons.columbus.search.aggregation.bucket.FiltersAggregation;
import com.phonepe.commons.columbus.search.aggregation.bucket.HistogramAggregation;
import com.phonepe.commons.columbus.search.aggregation.bucket.RangeAggregation;
import com.phonepe.commons.columbus.search.aggregation.bucket.SamplerAggregation;
import com.phonepe.commons.columbus.search.aggregation.bucket.TermsAggregation;
import com.phonepe.commons.columbus.search.aggregation.metrics.CardinalityAggregation;
import com.phonepe.commons.columbus.search.aggregation.metrics.StatsAggregation;
import com.phonepe.commons.columbus.search.aggregation.metrics.TopHitsAggregation;
import com.phonepe.commons.columbus.search.aggregator.Aggregator;
import lombok.NonNull;

/**
 * Represents the result generated by an {@link Aggregator}.
 */
@JsonClassDescription("Interface for aggregation results produced by executing aggregators on search results")
@JsonTypeInfo(
        use = JsonTypeInfo.Id.NAME,
        include = JsonTypeInfo.As.EXISTING_PROPERTY,
        property = "type"
)
@JsonSubTypes({
        // Metrics aggregation results
        @JsonSubTypes.Type(CardinalityAggregation.class),
        @JsonSubTypes.Type(StatsAggregation.class),
        @JsonSubTypes.Type(TopHitsAggregation.class),
        // Bucket aggregation results
        @JsonSubTypes.Type(FilterAggregation.class),
        @JsonSubTypes.Type(FiltersAggregation.class),
        @JsonSubTypes.Type(HistogramAggregation.class),
        @JsonSubTypes.Type(RangeAggregation.class),
        @JsonSubTypes.Type(SamplerAggregation.class),
        @JsonSubTypes.Type(TermsAggregation.class)
})
public interface Aggregation {

    @NonNull
    @JsonPropertyDescription("Name of the aggregation matching the aggregator that produced this result")
    String getName();

    @NonNull
    @JsonPropertyDescription("Type identifier of the aggregation result")
    String getType();
}
