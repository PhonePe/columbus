package com.phonepe.platform.columbus.internal.registry;

import com.phonepe.platform.columbus.registry.Registry;
import lombok.Builder;
import lombok.NonNull;

import java.util.Optional;
import java.util.function.Function;

/**
 * A registry which uses a sequence of keys to fetch the value corresponding to the key.
 * <p>
 * The sequence is defined by the {@link #nextKeyFunction} which is expected to return an optional next key to use in
 * case no value is registered for the given key. The registry repeatedly tries to fetch a value with next key, until
 * a value is found, or no next key is generated by the function.
 *
 * @param <K> the type of the key.
 * @param <V> the type of the values.
 */
@Builder
public class HierarchicalKeyRegistry<K, V> implements Registry<K, V> {

    @NonNull
    private final Function<K, Optional<? extends K>> nextKeyFunction;

    @NonNull
    private final Registry<? super K, ? extends V> registry;

    @Override
    public Optional<? extends V> get(final K key) {
        final var value = registry.get(key);
        if (value.isPresent()) {
            return value;
        }
        return nextKeyFunction.apply(key).flatMap(this::get);
    }
}
